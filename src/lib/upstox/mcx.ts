/**
 * Server-only: the listed MCX crude oil, gold and natural gas option contracts, from
 * Upstox's public instrument file (no token needed).
 *
 * The indices get their contracts from `/v2/option/contract` (see
 * contracts.ts), but that endpoint is asked for an *underlying*, and a
 * commodity option's underlying is one particular monthly futures contract —
 * a key that changes every month and that nothing else here knows. The
 * instrument file lists every option together with that underlying key, so it
 * answers all of these at once:
 *   - which contract is this position's bare `MCX_FO|584900`? (positions),
 *   - which strikes does an expiry have, and what are their keys? (the chain
 *     in mcxChain.ts - Upstox's own `/v2/option/chain` answers an MCX
 *     underlying with an empty list, so the chain is assembled from quotes), and
 *   - which futures contract is the spot of that expiry?
 *
 * It is ~8 MB once unzipped and regenerated by Upstox every morning, so it is
 * fetched at most once per IST day and only the four underlyings this app
 * tracks are kept.
 */

import { gunzipSync } from "node:zlib";

import { istDateString } from "@/lib/calculateStrategy";
import { COMMODITY_INSTRUMENTS, type CommodityInstrument } from "@/lib/types";
import type { UpstoxGetError } from "@/lib/upstox/api";
import type { OptionContract } from "@/lib/upstox/contracts";

const MCX_INSTRUMENTS_URL = "https://assets.upstox.com/market-quote/instruments/exchange/MCX.json.gz";
const IST_OFFSET_MS = 5.5 * 3_600_000;

/** Every key of a position or a chain that belongs to MCX starts like this. */
export const MCX_KEY_PREFIX = "MCX_FO|";

export type McxStrike = { strike: number; ce: string | null; pe: string | null };

/** The contract a commodity is quoted on: its nearest futures month that hasn't expired yet. */
export type McxFuture = {
  /** Upstox's underlying symbol, e.g. "CRUDEOIL" - the commodity's identity across month rolls. */
  symbol: string;
  /** The exchange's own name for it ("CRUDE OIL") - the Mini and full-size contracts share one. */
  name: string;
  key: string;
  /** yyyy-mm-dd of the contract's expiry. */
  expiry: string;
  /** "CRUDEOIL FUT 19 NOV 26". */
  tradingSymbol: string;
};

export type McxContracts = {
  /** Every MCX commodity's current-month future, by underlying symbol (CRUDEOIL, GOLD, COPPER, ...). */
  futures: Map<string, McxFuture>;
  /** Option contract by Upstox instrument_key. */
  contracts: Map<string, OptionContract>;
  /** The futures contract each option expiry is written on, as `${instrument}|${yyyy-mm-dd}` → instrument_key. */
  underlyingKeys: Map<string, string>;
  /** The strike ladder of each expiry, as `${instrument}|${yyyy-mm-dd}` → strikes ascending. */
  ladders: Map<string, McxStrike[]>;
  /** Every listed expiry per instrument, soonest first. */
  expiries: Map<CommodityInstrument, string[]>;
};

type McxResult = McxContracts | UpstoxGetError;

export function isMcxError(result: McxResult): result is UpstoxGetError {
  return "error" in result;
}

export function mcxUnderlyingKeyId(instrument: CommodityInstrument, expiry: string): string {
  return `${instrument}|${expiry}`;
}

function isCommodity(value: unknown): value is CommodityInstrument {
  return typeof value === "string" && (COMMODITY_INSTRUMENTS as readonly string[]).includes(value);
}

/** The file gives `expiry` as epoch milliseconds (23:59 IST on the expiry day). */
function toIsoDate(value: unknown): string | null {
  if (typeof value === "number" && Number.isFinite(value)) return new Date(value + IST_OFFSET_MS).toISOString().slice(0, 10);
  if (typeof value === "string" && /^\d{4}-\d{2}-\d{2}/.test(value)) return value.slice(0, 10);
  return null;
}

function positive(value: unknown): number | null {
  const n = typeof value === "string" ? Number(value) : value;
  return typeof n === "number" && Number.isFinite(n) && n > 0 ? n : null;
}

/**
 * Reduces the raw instrument rows to the options of the tracked underlyings, and the current-month future of every
 * commodity. `todayIso` (IST) decides which months are still live. Exported for testing.
 */
export function parseMcxInstruments(rows: unknown, todayIso: string = istDateString(Date.now())): McxContracts | null {
  if (!Array.isArray(rows)) return null;

  const futures = new Map<string, McxFuture>();
  const contracts = new Map<string, OptionContract>();
  const underlyingKeys = new Map<string, string>();
  const strikesByExpiry = new Map<string, Map<number, McxStrike>>();
  const expirySets = new Map<CommodityInstrument, Set<string>>();

  for (const row of rows as Record<string, unknown>[]) {
    if (row.segment === "MCX_FO" && row.instrument_type === "FUT") {
      const symbol = row.underlying_symbol;
      const key = row.instrument_key;
      const expiry = toIsoDate(row.expiry);
      // The index futures (MCXBULLDEX, MCXMETLDEX) are not commodities, and a month past its expiry is no quote at all.
      if (typeof symbol !== "string" || typeof key !== "string" || !expiry || expiry < todayIso) continue;
      const held = futures.get(symbol);
      if (!held || expiry < held.expiry) {
        futures.set(symbol, {
          symbol,
          name: typeof row.name === "string" ? row.name : symbol,
          key,
          expiry,
          tradingSymbol: typeof row.trading_symbol === "string" ? row.trading_symbol : symbol,
        });
      }
      continue;
    }

    const optionType = row.instrument_type;
    if (row.segment !== "MCX_FO" || (optionType !== "CE" && optionType !== "PE")) continue;
    const instrument = row.underlying_symbol;
    if (!isCommodity(instrument)) continue;

    const key = row.instrument_key;
    const underlyingKey = row.underlying_key;
    const expiry = toIsoDate(row.expiry);
    const strike = positive(row.strike_price);
    // Upstox counts MCX positions in lots and values them with a per-lot multiplier (crude 100, gold 100 - the
    // premium is per barrel / per 10 g), which the file calls `qty_multiplier`. That is the "units per lot" here.
    const lotSize = positive(row.qty_multiplier) ?? positive(row.lot_size);
    if (typeof key !== "string" || typeof underlyingKey !== "string" || !expiry || !strike || !lotSize) continue;

    contracts.set(key, { instrument, strike, optionType, expiry, lotSize });
    const expiryId = mcxUnderlyingKeyId(instrument, expiry);
    underlyingKeys.set(expiryId, underlyingKey);
    const strikes = strikesByExpiry.get(expiryId) ?? new Map<number, McxStrike>();
    const slot = strikes.get(strike) ?? { strike, ce: null, pe: null };
    if (optionType === "CE") slot.ce = key;
    else slot.pe = key;
    strikes.set(strike, slot);
    strikesByExpiry.set(expiryId, strikes);
    const set = expirySets.get(instrument) ?? new Set<string>();
    set.add(expiry);
    expirySets.set(instrument, set);
  }

  const expiries = new Map<CommodityInstrument, string[]>();
  for (const [instrument, set] of expirySets) expiries.set(instrument, [...set].sort());
  const ladders = new Map<string, McxStrike[]>();
  for (const [id, strikes] of strikesByExpiry) ladders.set(id, [...strikes.values()].sort((a, b) => a.strike - b.strike));
  return { futures, contracts, underlyingKeys, ladders, expiries };
}

/** Strikes fetched each side of the money. Crude steps 50 (±1,500), gold 500 (±15,000), natural gas 5 (±150) - well beyond a sensible strike. */
export const MCX_CHAIN_WINDOW = 30;
/** A caller can't ask for the whole ladder by listing every strike. */
const MAX_EXTRA_STRIKES = 20;

/** The strikes to fetch: a window around the money, plus every strike in `extraStrikes` that exists. Exported for testing. */
export function selectStrikes(ladder: McxStrike[], spot: number | null, extraStrikes: number[], window = MCX_CHAIN_WINDOW): McxStrike[] {
  if (ladder.length === 0) return [];
  let atm = Math.floor(ladder.length / 2);
  if (spot !== null && spot > 0) {
    atm = ladder.reduce((best, s, i) => (Math.abs(s.strike - spot) < Math.abs(ladder[best].strike - spot) ? i : best), 0);
  }
  const wanted = new Set(extraStrikes.slice(0, MAX_EXTRA_STRIKES));
  return ladder.filter((s, i) => Math.abs(i - atm) <= window || wanted.has(s.strike));
}

let cache: { day: string; data: McxContracts } | null = null;
// Several polls can land together on a cold start — they share the one download.
let inflight: Promise<McxResult> | null = null;

async function fetchMcxContracts(): Promise<McxResult> {
  let response: Response;
  try {
    response = await fetch(MCX_INSTRUMENTS_URL, { cache: "no-store" });
  } catch {
    return { error: "Couldn't reach Upstox's MCX contract list.", status: 502 };
  }
  if (!response.ok) return { error: `Upstox's MCX contract list returned ${response.status}`, status: 502 };

  let rows: unknown;
  try {
    rows = JSON.parse(gunzipSync(Buffer.from(await response.arrayBuffer())).toString("utf8"));
  } catch {
    return { error: "Upstox's MCX contract list couldn't be read.", status: 502 };
  }
  const parsed = parseMcxInstruments(rows);
  if (!parsed || parsed.contracts.size === 0) {
    return { error: "Upstox's MCX contract list was missing the expected data.", status: 502 };
  }
  return parsed;
}

/** Cached for the IST day: contracts are listed before a session, not during one. Only a complete result is kept. */
export function getMcxContracts(): Promise<McxResult> {
  const today = istDateString(Date.now());
  if (cache?.day === today) return Promise.resolve(cache.data);
  if (inflight) return inflight;

  inflight = fetchMcxContracts()
    .then((result) => {
      if (!isMcxError(result)) cache = { day: today, data: result };
      return result;
    })
    .finally(() => {
      inflight = null;
    });
  return inflight;
}
